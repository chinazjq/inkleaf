export function resolveLang(setting, systemLang) {
  if (setting === 'zh-CN' || setting === 'en') return setting;
  return String(systemLang || navigator.language || '').toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function t(lang, key, vars = null) {
  const table = DICT[lang === 'en' ? 'en' : 'zh-CN'];
  let out = table[key] ?? DICT['zh-CN'][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

export function applyStaticI18n(shellRoot, lang) {
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
  for (const el of shellRoot.querySelectorAll('[data-i18n]')) {
    el.textContent = t(lang, el.dataset.i18n);
  }
  for (const el of shellRoot.querySelectorAll('[data-i18n-placeholder]')) {
    el.placeholder = t(lang, el.dataset.i18nPlaceholder);
  }
  for (const el of shellRoot.querySelectorAll('[data-i18n-aria]')) {
    el.setAttribute('aria-label', t(lang, el.dataset.i18nAria));
  }
  for (const el of shellRoot.querySelectorAll('[data-i18n-title]')) {
    el.title = t(lang, el.dataset.i18nTitle);
  }
}
